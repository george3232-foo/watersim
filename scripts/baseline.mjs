import { chromium } from 'playwright';
const browser = await chromium.launch({ headless: true, args: ['--use-gl=angle','--use-angle=gl','--ignore-gpu-blocklist','--enable-gpu','--disable-gpu-sandbox'] });
const page = await browser.newPage({ viewport: { width: 1152, height: 720 }, deviceScaleFactor: 1 });
page.setDefaultTimeout(180000);
const logs=[]; page.on('console',m=>{if(m.type()==='error')logs.push(m.text())}); page.on('pageerror',e=>logs.push('ERR '+e.message));
await page.goto('http://localhost:5173/?quality=low',{waitUntil:'domcontentloaded'});
await page.waitForFunction(()=>window.__pond&&window.__pond.ready,null,{timeout:90000});
await page.evaluate(()=>{const a=window.__pond;a.controls.autoRotate=false;a.controls.update();});
await page.waitForTimeout(1500);
await page.screenshot({path:'/tmp/baseline-now.png'});
await page.evaluate(()=>{window.__pond.splash.group.visible=false;});
await page.waitForTimeout(500);
await page.screenshot({path:'/tmp/baseline-nosplash.png'});
console.log('logs',logs.slice(0,5).join(' | '));
await browser.close();
