import { chromium } from 'playwright';
const browser = await chromium.launch({ headless: true, args: ['--use-gl=angle','--use-angle=gl','--ignore-gpu-blocklist','--enable-gpu','--disable-gpu-sandbox'] });
const page = await browser.newPage({ viewport: { width: 1152, height: 720 } });
page.setDefaultTimeout(120000);
const errors=[]; page.on('console',m=>{if(m.type()==='error')errors.push(m.text().slice(0,300));}); page.on('pageerror',e=>errors.push('PE '+e.message));
await page.goto('http://localhost:5173/?quality=low', { waitUntil: 'domcontentloaded', timeout: 120000 });
await page.waitForFunction(() => window.__pond && window.__pond.ready, null, { timeout: 90000 });
await page.waitForTimeout(3500);
const shot = async (name) => { await page.waitForTimeout(500); await page.screenshot({ path: `/tmp/ab-${name}.png` }); };
await shot('0-base');
await page.evaluate(() => { window.__pond.engine.finalMat.uniforms.uBloom.value = 0; });
await shot('1-nobloom');
await page.evaluate(() => { window.__pond.water.uniforms.uDebug.value = 6; });
await shot('2-scenecol');
await page.evaluate(() => { window.__pond.water.uniforms.uDebug.value = 7; });
await shot('3-normals');
await page.evaluate(() => { const a=window.__pond; a.water.uniforms.uDebug.value = 0; a.water.mesh.visible = false; });
await shot('4-nowater');
await page.evaluate(() => { const a=window.__pond; a.water.mesh.visible = true; a.water.uniforms.uRefraction.value = 0; });
await shot('5-norefract');
await page.evaluate(() => { const a=window.__pond; a.water.uniforms.uRefraction.value = 1; a.sim.setWind(0,0); a.sim.rain=0; a.engine.finalMat.uniforms.uBloom.value = 0.2; });
await page.waitForTimeout(2500);
await shot('6-calm');
console.log({errors});
await browser.close();
