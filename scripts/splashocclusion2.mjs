import { chromium } from 'playwright';
const browser = await chromium.launch({ headless: true, args: ['--use-gl=angle','--use-angle=gl','--ignore-gpu-blocklist','--enable-gpu','--disable-gpu-sandbox'] });
const page = await browser.newPage({ viewport: { width: 1000, height: 640 }, deviceScaleFactor: 1 });
page.setDefaultTimeout(120000);
await page.route('**/@vite/client*', (route) => route.fulfill({ status: 200, contentType: 'application/javascript', body: 'export const createHotContext=()=>({on(){},off(){},send(){},accept(){},dispose(){},decline(){},invalidate(){}});export const injectQuery=(u)=>u;export const removeTimestampQuery=(u)=>u;export const updateStyle=()=>{};' }));
const logs=[]; page.on('console',m=>{if(m.type()==='error'||m.type()==='warning')logs.push(m.text())}); page.on('pageerror',e=>logs.push('ERR '+e.message));
await page.goto('http://localhost:5173/?quality=low', { waitUntil: 'domcontentloaded' });
await page.waitForFunction(() => window.__pond && window.__pond.ready, null, { timeout: 90000 });
await page.waitForTimeout(800);
await page.evaluate(() => {
	const a = window.__pond;
	a.controls.autoRotate = false;
	a.camera.position.set(3.4, 1.5, 3.4);
	a.controls.target.set(0, 0.15, 0);
	a.controls.update();
	cancelAnimationFrame(a._raf); a._raf = 0;
	const jetty = a.props.group.getObjectByName('jetty');
	const blocker = jetty.clone();
	blocker.position.set(1.05, 0.45, 1.05);
	blocker.scale.setScalar(4.0);
	blocker.rotation.set(0, 0.6, 0.1);
	a.scene.add(blocker); window.__cube = blocker;
	const sp = a.splash;
	sp.splashAt(0, 0, 0.5, { radius: 0.075, vy: -8 });
	for (let i = 0; i < 8; i++) sp.update(0.035, a.time + i * 0.035);
	const render = () => {
		a.engine.renderScene(a.scene, a.camera, a.sky);
		a.engine.renderComposite(a.scene, a.water.scene, a.rainScene, a.camera);
		a.engine.post(a.time, a.sunScreen);
	};
	window.__render = render;
	render();
});
let st = await page.evaluate(() => { const sp=window.__pond.splash; let alive=0; for(let i=0;i<sp.maxDroplets;i++)alive+=sp._alive[i]; return {alive,draw:sp._particleGeo.drawRange.count,rings:sp._rings.filter(r=>r.active).length}; });
console.log('state', JSON.stringify(st));
await page.screenshot({ path: '/tmp/splash-occluded.png' });
await page.evaluate(() => { const a=window.__pond; window.__cube.visible=false; window.__render(); });
await page.waitForTimeout(150);
await page.screenshot({ path: '/tmp/splash-unoccluded.png' });
console.log('logs', logs.slice(0,6).join(' | '));
await browser.close();
